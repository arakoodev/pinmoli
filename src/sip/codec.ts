/**
 * Codec data model, lookup, and transcoding
 */

import { execFileSync } from 'child_process';
import { writeFileSync, readFileSync, unlinkSync } from 'fs';

export interface CodecInfo {
  name: string;
  payloadType: number;
  clockRate: number;
  sampleRate: number;
  packetSize: number; // bytes per 20ms packet
  wavFormatCode: number; // WAV fmt chunk format code (7=mulaw, 6=alaw, 0xFFFF=unknown/raw)
  ffmpegCodec: string; // ffmpeg -acodec value for encoding
}

export const CODEC_TABLE: Record<string, CodecInfo> = {
  PCMU: {
    name: 'PCMU',
    payloadType: 0,
    clockRate: 8000,
    sampleRate: 8000,
    packetSize: 160,
    wavFormatCode: 7,
    ffmpegCodec: 'pcm_mulaw',
  },
  PCMA: {
    name: 'PCMA',
    payloadType: 8,
    clockRate: 8000,
    sampleRate: 8000,
    packetSize: 160,
    wavFormatCode: 6,
    ffmpegCodec: 'pcm_alaw',
  },
  G722: {
    name: 'G722',
    payloadType: 9,
    clockRate: 8000, // G.722 uses 8000 in RTP clock despite 16kHz audio (RFC 3551)
    sampleRate: 16000,
    packetSize: 160, // 80 bytes per 10ms at 64kbps, but 160 bytes per 20ms (matches RTP convention)
    wavFormatCode: 0xFFFF, // No standard WAV code — save raw, decode via ffmpeg
    ffmpegCodec: 'g722',
  },
  opus: {
    name: 'opus',
    payloadType: 111,
    clockRate: 48000,
    sampleRate: 48000,
    packetSize: 960, // 20ms at 48kHz (variable, but this is the timestamp increment)
    wavFormatCode: 0xFFFF,
    ffmpegCodec: 'libopus',
  },
};

/**
 * Look up codec by RTP payload type number
 */
export function codecByPayloadType(pt: number): CodecInfo | undefined {
  return Object.values(CODEC_TABLE).find(c => c.payloadType === pt);
}

/**
 * Look up codec by name (case-insensitive)
 */
export function codecByName(name: string): CodecInfo | undefined {
  // Try exact match first
  if (CODEC_TABLE[name]) return CODEC_TABLE[name];
  // Case-insensitive fallback
  const upper = name.toUpperCase();
  return Object.values(CODEC_TABLE).find(c => c.name.toUpperCase() === upper);
}

