/**
 * Transcode PCMU audio data to the target codec.
 * - PCMU → PCMU: identity (returns same buffer)
 * - PCMU → PCMA: table lookup (pure JS, no deps)
 * - PCMU → G722: ffmpeg subprocess
 */
export function transcodePcmuTo(pcmuData: Buffer, targetCodec: CodecInfo): Buffer {
  if (targetCodec.name === 'PCMU') {
    return pcmuData;
  }

  if (targetCodec.name === 'PCMA') {
    return transcodeMulawToAlaw(pcmuData);
  }

  if (targetCodec.name === 'G722') {
    return transcodePcmuToG722(pcmuData);
  }

  throw new Error(
    `Codec ${targetCodec.name} (PT=${targetCodec.payloadType}) transcoding not implemented. ` +
    `Supported: PCMU, PCMA, G722.`
  );
}

/**
 * Mu-law → A-law transcoding via lookup table (pure JS)
 */
function transcodeMulawToAlaw(pcmuData: Buffer): Buffer {
  const output = Buffer.allocUnsafe(pcmuData.length);
  for (let i = 0; i < pcmuData.length; i++) {
    output[i] = MULAW_TO_ALAW[pcmuData[i]];
  }
  return output;
}

/**
 * PCMU → G722 transcoding via ffmpeg.
 * Decodes mu-law 8kHz → PCM 16kHz → G722.
 */
function transcodePcmuToG722(pcmuData: Buffer): Buffer {
  const tmpIn = `/tmp/pinmoli-transcode-${Date.now()}-${process.pid}-in.raw`;
  const tmpOut = `/tmp/pinmoli-transcode-${Date.now()}-${process.pid}-out.raw`;

  try {
    writeFileSync(tmpIn, pcmuData);

    execFileSync('ffmpeg', [
      '-f', 'mulaw', '-ar', '8000', '-ac', '1', '-i', tmpIn,
      '-ar', '16000', '-acodec', 'g722', '-f', 'g722', '-y', tmpOut,
    ], { stdio: 'pipe', timeout: 10000 });

    return readFileSync(tmpOut);
  } finally {
    try { unlinkSync(tmpIn); } catch { /* ignore */ }
    try { unlinkSync(tmpOut); } catch { /* ignore */ }
  }
}
